// MaxRound is the highest valid round number, 2^53.
// Larger numbers lose precision in the JSON numbers of some clients.
const MaxRound uint64 = 1 << 53

// Chain holds the fixed parameters of one drand chain.
type Chain struct {
	BeaconID   string
	ChainHash  string
	PublicKey  []byte
	SchemeID   string
	Genesis    int64 // Unix seconds.
	Period     int64 // Seconds.
	SigLen     int
	PrevSigLen int
}

// Round is one round of a chain.
type Round struct {
	Number  uint64
	Sig     []byte
	PrevSig []byte
}

